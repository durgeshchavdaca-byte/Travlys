export function getPost(slug) {
  return BLOG_POSTS.find((p) => p.slug === slug) || null
}

export const BLOG_CATEGORIES = [...new Set(BLOG_POSTS.map((p) => p.category))]

// Guides linked from a destination's visa page: posts whose CTA points at it,
// newest first.
export function getPostsForDestination(slug) {
  return BLOG_POSTS.filter((p) => p.cta?.slug === slug).sort((a, b) =>
    (b.updated || b.date).localeCompare(a.updated || a.date),
  )
}

// Newest posts first, by last update.
export function getLatestPosts(n = 3) {
  return [...BLOG_POSTS].sort((a, b) => (b.updated || b.date).localeCompare(a.updated || a.date)).slice(0, n)
}
